                                <p class="text-slate-300 text-sm mt-2">A: ค่าน้ำ MY มีทั้งติดลบ (เสียไม่เต็ม) และบวก, ค่าน้ำ HK คิดคำนวณกำไรล้วนๆ โดยไม่รวมเงินทุน ส่วนค่าน้ำ EU คิดคำนวณผลตอบแทนรวมเงินทุนทั้งหมด (คิดจาก ทุน x ค่าน้ำ)</p>
